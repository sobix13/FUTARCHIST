def fingerprint(value):
    return hashlib.sha256(value.encode('utf-8')).hexdigest()


def built_in_copy(value):
    return COPY_FINGERPRINTS.get(fingerprint(value), value)


def upgrade_english(store):
    """Runs within the startup transaction. Custom copy remains unchanged."""
    if store.one("SELECT value FROM settings WHERE key='ui_english_v1'"):
        return
    from .forms import FIELDS
    from .management import TEXT_DEFAULTS
    for row in store.rows('SELECT key,value FROM text_settings'):
        value = built_in_copy(row['value'])
        expected = TEXT_DEFAULTS.get(row['key'])
        if row['key'].startswith('question:') and row['key'][9:] in FIELDS:
            expected = FIELDS[row['key'][9:]][0]
        if value != row['value'] and value == expected:
            store.db.execute('UPDATE text_settings SET value=?,version=version+1,updated_at=? WHERE key=?',
                             (value,store.clock(),row['key']))
    for row in store.rows('SELECT id,name,kind,creator FROM spaces'):
        name = row['name']
        user = store.one('SELECT name FROM users WHERE id=?', (row['creator'],))
        if row['kind'] == 'personal' and row['creator'] in store.super_admin_ids and name == OLD_INBOX:
            name = 'Superadmin inbox'
        if row['kind'] == 'personal' and user and row['name'] == SPACE_PREFIX + user['name']:
            name = 'Workspace ' + user['name']
        if name != row['name']:
            store.db.execute('UPDATE spaces SET name=? WHERE id=?', (name,row['id']))
    for row in store.rows('SELECT id,name,creator,token FROM routes'):
        user = store.one('SELECT name FROM users WHERE id=?', (row['creator'],))
        name = row['name']
        if user and name == CODE_PREFIX + user['name']:
            name = 'Intake code ' + user['name']
        if row['token'] == 'public':
            name = 'Public intake'
        if name != row['name']:
            store.db.execute('UPDATE routes SET name=? WHERE id=?', (name,row['id']))
    for row in store.rows('SELECT user_id,data FROM native_flows'):
        data = json.loads(row['data'])
        for field in data.get('form', {}).get('fields', []):
            if isinstance(field.get('title'),str):
                field['title'] = built_in_copy(field['title'])
        store.db.execute('UPDATE native_flows SET data=? WHERE user_id=?',
                         (json.dumps(data,ensure_ascii=False),row['user_id']))
    store.db.execute("DELETE FROM settings WHERE key LIKE 'lang:%'")
    store.db.execute("INSERT INTO settings(key,value) VALUES('ui_english_v1','1')")
